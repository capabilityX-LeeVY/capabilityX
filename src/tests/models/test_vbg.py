def validate_vbg_batch(image_directory, output_dir=None):
    """
    Validate multiple VBG test images in a directory.
    
    Args:
        image_directory (str): Path to directory containing VBG test images
        output_dir (str, optional): Directory to save results
    
    Returns:
        list: List of validation results
    """
    if not os.path.exists(image_directory):
        raise FileNotFoundError(f"Image directory not found: {image_directory}")
    
    # Get all image files
    image_extensions = {'.png', '.jpg', '.jpeg', '.bmp', '.gif', '.tiff'}
    image_files = [
        os.path.join(image_directory, f) 
        for f in os.listdir(image_directory) 
        if os.path.splitext(f.lower())[1] in image_extensions
    ]
    
    if not image_files:
        print(f"❌ No image files found in {image_directory}")
        return []
    
    print(f"📁 Found {len(image_files)} VBG test image(s) to validate")
    
    results = []
    for i, image_path in enumerate(image_files, 1):
        print(f"\n🖼️  Validating image {i}/{len(image_files)}: {os.path.basename(image_path)}")
        try:
            result_path = test_vbg_executive_office_validation(image_path, output_dir=output_dir)
            if result_path:
                results.append(result_path)
        except Exception as e:
            print(f"❌ Error validating {image_path}: {str(e)}")
    
    print(f"\n✅ Batch VBG validation completed. {len(results)} reports generated.")
    return results


